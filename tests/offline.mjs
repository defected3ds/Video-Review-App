import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { readFileSync, existsSync } from 'node:fs';
import { once } from 'node:events';
import path from 'node:path';
import { root } from './helpers.mjs';
const html=readFileSync(path.join(root,'dist-offline/Pipelife-interactive.html'),'utf8');
const server=createServer((req,res)=>{if(req.url==='/'){res.writeHead(200,{'Content-Type':'text/html'});res.end(html);}else{res.writeHead(404);res.end();}});
server.listen(0,'127.0.0.1');await once(server,'listening');
const browser=await chromium.launch({headless:true,executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||(existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined),args:['--no-sandbox']});
const errors=[],apiRequests=[];
try {
 const context=await browser.newContext({viewport:{width:1440,height:1000}}),page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));page.on('request',req=>{if(/\/api\//.test(req.url()))apiRequests.push(req.url());});
 await page.goto(`http://127.0.0.1:${server.address().port}/`);
 await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2);
 await context.setOffline(true);
 await page.getByRole('button',{name:'Play video',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('video').currentTime>.2);
 await page.getByRole('button',{name:'Pause video',exact:true}).click();
 await page.getByRole('button',{name:'Pin comment',exact:true}).click();
 const rect=await page.locator('.video-overlay').boundingBox();
 await page.mouse.click(rect.x+rect.width*.4,rect.y+rect.height*.4);
 await page.getByRole('button',{name:'Pencil',exact:true}).click();
 await page.mouse.move(rect.x+rect.width*.3,rect.y+rect.height*.3);await page.mouse.down();await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.5,{steps:10});await page.mouse.up();
 assert.equal(await page.getByLabel('Source frame rate').isDisabled(),true);
 await page.getByLabel('Comment',{exact:true}).fill('Offline hotspot and pencil feedback');
 await page.getByRole('button',{name:'Send comment'}).click();
 await page.getByRole('button',{name:'Offline hotspot and pencil feedback',exact:true}).click();
 await page.locator('.hotspot.active').waitFor();assert.ok(await page.locator('polyline').count());
 await page.getByLabel('Review status').selectOption('Approved');
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Export feedback'}).click();
 const download=await downloadPromise;const feedback=JSON.parse(readFileSync(await download.path(),'utf8'));
 assert.equal(feedback.status,'Approved');assert.ok(feedback.comments.some(c=>c.hotspot&&c.body==='Offline hotspot and pencil feedback'));assert.ok(feedback.comments.some(c=>c.body==='Drawing'&&c.annotations.length));
 console.log('PASS: embedded video, playback, hotspot, pencil, status and feedback export with network offline');
 await context.setOffline(false);await page.reload();
 await page.getByRole('button',{name:'Offline hotspot and pencil feedback',exact:true}).waitFor();
 assert.equal(await page.getByLabel('Review status').inputValue(),'Approved');
 await page.locator('article.comment').filter({has:page.getByRole('button',{name:'Offline hotspot and pencil feedback',exact:true})}).getByRole('button',{name:'Resolve comment by Reviewer',exact:true}).click();
 await page.getByLabel('Filter comments').selectOption('Resolved');await page.getByRole('button',{name:'Offline hotspot and pencil feedback',exact:true}).waitFor();
 await context.setOffline(true);
 await page.getByLabel('Open local video').setInputFiles(path.join(root,'public/demo.mp4'));
 await page.waitForFunction(()=>document.querySelector('.video-stage video')?.currentSrc.startsWith('blob:')&&document.querySelector('.video-stage video').readyState>=2);
 await page.getByLabel('Source frame rate').selectOption('30');
 await page.waitForFunction(()=>document.querySelector('.video-stage video')?.readyState>=2);
 await page.getByLabel('Comment',{exact:true}).fill('My local clip feedback');await page.getByRole('button',{name:'Send comment'}).click();
 await page.getByRole('button',{name:'My local clip feedback',exact:true}).waitFor();
 await context.setOffline(false);await page.reload();
 await page.getByLabel('Open local video').setInputFiles(path.join(root,'public/demo.mp4'));
 await page.getByRole('button',{name:'My local clip feedback',exact:true}).waitFor();assert.equal(await page.getByLabel('Source frame rate').inputValue(),'30');
 await page.setViewportSize({width:390,height:844});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 assert.deepEqual(apiRequests,[]);assert.deepEqual(errors,[]);
 console.log('PASS: browser persistence, resolving, local video import, retained feedback after reopening the clip, mobile layout, and no API requests');
 const isolated=await browser.newContext();await isolated.setOffline(true);const isolatedPage=await isolated.newPage();isolatedPage.on('pageerror',e=>errors.push(e.message));await isolatedPage.setContent(html);await isolatedPage.waitForFunction(()=>document.querySelector('video')?.readyState>=2);assert.deepEqual(errors,[]);await isolated.close();
 console.log('PASS: self-contained HTML runs without a host or network, with in-memory fallback when storage is unavailable');
} finally {await browser.close();server.close();}
